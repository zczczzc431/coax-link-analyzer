#ifndef SCOPE_STATS683_H
#define SCOPE_STATS683_H

#include <math.h>
#include <stddef.h>
#include <stdint.h>

#define SS683_CAP 16u
#define SS683_MAX_GAP_US UINT64_C(1000000)

/* Sparse completed-frame observations, never concatenated RAW samples.
 * Initialize with ss683_reset() (or zero-initialize) before first use.
 * The fields are implementation state; callers must not edit the ring. */
struct ss683_sample {
    uint32_t token;
    uint64_t observed_us;
    double hz;
};

struct ss683_state {
    struct ss683_sample sample[SS683_CAP];
    unsigned n;
    unsigned head; /* Oldest observation, not the next insertion slot. */
    const char *reason; /* Most recent reset cause; not a quality guarantee. */
};

struct ss683_summary {
    unsigned n;
    int valid;
    double mean_hz, sd_hz, min_hz, max_hz, pp_hz;
    uint64_t span_us, max_gap_us;
    const char *reason;
};

/* reason is borrowed, not copied: pass only a static string literal (or NULL).
 * All reasons generated by this header are static string literals as well. */
static inline void ss683_reset(struct ss683_state *s, const char *reason) {
    if (!s) return;
    *s = (struct ss683_state){0};
    s->reason = reason ? reason : "RESET";
}

/* 1: accepted; 0: duplicate last token, absolutely no state change;
 * -1: rejected and cleared (except NULL state, which cannot be cleared).
 * Invalid input takes precedence over duplicate detection. Different tokens
 * require strictly increasing observation times. Modulo token ordering accepts
 * a forward distance in (0, 2^31); the ambiguous half-circle is rejected.
 * Token zero is always invalid, including at wrap. No frequency jump filter. */
static inline int ss683_push(struct ss683_state *s, uint32_t token,
                             uint64_t observed_us, double hz, int valid) {
    if (!s) return -1;
    if (!valid) {
        ss683_reset(s, "INVALID_FRAME");
        return -1;
    }
    if (!isfinite(hz)) {
        ss683_reset(s, "NONFINITE");
        return -1;
    }
    if (hz <= 0.0) {
        ss683_reset(s, "NONPOSITIVE");
        return -1;
    }
    if (!token) {
        ss683_reset(s, "TOKEN_ZERO");
        return -1;
    }
    if (!observed_us) {
        ss683_reset(s, "TIME_ZERO");
        return -1;
    }
    if (s->n > SS683_CAP || s->head >= SS683_CAP) {
        ss683_reset(s, "STATE_INVALID");
        return -1;
    }
    if (s->n) {
        unsigned last = (s->head + s->n - 1u) % SS683_CAP;
        const struct ss683_sample *p = &s->sample[last];
        if (token == p->token) return 0;
        if (observed_us <= p->observed_us) {
            ss683_reset(s, "TIME_ORDER");
            return -1;
        }
        if ((uint32_t)(token - p->token) >= UINT32_C(0x80000000)) {
            ss683_reset(s, "TOKEN_ORDER");
            return -1;
        }
        if (observed_us - p->observed_us > SS683_MAX_GAP_US)
            ss683_reset(s, "GAP");
    }
    unsigned at = (s->head + s->n) % SS683_CAP;
    s->sample[at] = (struct ss683_sample){token, observed_us, hz};
    if (s->n < SS683_CAP) s->n++;
    else s->head = (s->head + 1u) % SS683_CAP;
    return 1;
}

/* Population SD of observed per-frame frequencies, not SEM, calibration
 * uncertainty, continuous-counter accuracy, or oscillator aperture jitter.
 * valid means n >= 2, NOT that the 16-observation window is full or current.
 * span/gap use observation timestamps only. A caller must label freshness,
 * warmup, pause, context changes and invalid instantaneous data separately. */
static inline void ss683_summarize(const struct ss683_state *s,
                                  struct ss683_summary *o) {
    if (!o) return;
    *o = (struct ss683_summary){0};
    o->mean_hz = o->sd_hz = o->min_hz = o->max_hz = o->pp_hz = NAN;
    o->reason = "NULL_STATE";
    if (!s) return;
    o->reason = s->reason ? s->reason : "RESET";
    if (s->n > SS683_CAP || s->head >= SS683_CAP) {
        o->reason = "STATE_INVALID";
        return;
    }
    o->n = s->n;
    if (!s->n) return;

    /* Pass 1: Welford mean of offsets from the first observation. Keeping
     * the offset mean unrounded until pass 2 preserves small fluctuations
     * around a large carrier. Iterate oldest to newest through the ring. */
    const struct ss683_sample *first = &s->sample[s->head];
    double origin = first->hz, mean_offset = 0.0;
    double lo = origin, hi = origin;
    uint64_t previous_us = first->observed_us;
    for (unsigned i = 0; i < s->n; ++i) {
        const struct ss683_sample *p = &s->sample[(s->head + i) % SS683_CAP];
        double d = p->hz - origin;
        mean_offset += (d - mean_offset) / (double)(i + 1u);
        if (p->hz < lo) lo = p->hz;
        if (p->hz > hi) hi = p->hz;
        if (i) {
            uint64_t gap = p->observed_us - previous_us;
            if (gap > o->max_gap_us) o->max_gap_us = gap;
        }
        previous_us = p->observed_us;
    }
    o->mean_hz = origin + mean_offset;
    o->min_hz = lo;
    o->max_hz = hi;
    o->span_us = previous_us - first->observed_us;
    if (s->n < 2u) return;

    /* Pass 2: centered, scaled sum of squares. Unlike E[x*x]-E[x]^2,
     * this avoids carrier cancellation; scaling avoids squaring overflow
     * even when the positive finite observations span a very wide range. */
    double scale = 0.0, ssq = 1.0;
    for (unsigned i = 0; i < s->n; ++i) {
        double hz = s->sample[(s->head + i) % SS683_CAP].hz;
        double d = fabs((hz - origin) - mean_offset);
        if (d == 0.0) continue;
        if (d > scale) {
            double ratio = scale / d;
            ssq = 1.0 + ssq * ratio * ratio;
            scale = d;
        } else {
            double ratio = d / scale;
            ssq += ratio * ratio;
        }
    }
    o->sd_hz = scale == 0.0 ? 0.0 : scale * sqrt(ssq / (double)s->n);
    o->pp_hz = hi - lo;
    o->valid = 1;
}

#endif
